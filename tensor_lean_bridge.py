@dataclass
class LeanOutput:
    """A generated Lean 4 code fragment with certificate typing."""
    signature: Tuple[int, int, int]
    regime: Regime
    kappa: float
    cert_type: CertificateType
    lean_code: str
    fusion_energy: float
    recon_proxy: float
    fused_vector: np.ndarray = field(repr=False)


class TensorLeanBridge:
    """Bridge from tensor fusion to Lean 4 output.

    Pipeline:
        1. Encode signature as multiple modalities
        2. Fuse via TensorSketchFusion
        3. Classify fused output → certificate type
        4. Generate Lean 4 code with correct governance typing
    """

    def __init__(self, out_dim: int = 2048, cert_threshold: float = 0.7):
        self.fusion = TensorSketchFusion(out_dim=out_dim, seed=42)
        self.cert_threshold = cert_threshold
        self._prototypes: Dict[str, np.ndarray] = {}

    def build_prototypes(self, known_signatures: Dict[str, List[Tuple[int, int, int]]]):
        """Build regime prototypes from known signatures.

        Args:
            known_signatures: dict mapping regime name to list of (p,q,r) tuples
        """
        for regime, sigs in known_signatures.items():
            fused_vecs = []
            for p, q, r in sigs:
                fout = self._fuse_signature(p, q, r)
                fused_vecs.append(fout.fused)
            self._prototypes[regime] = np.mean(fused_vecs, axis=0)

    def _fuse_signature(self, p: int, q: int, r: int,
                         brain_patterns: Optional[Dict] = None) -> FusionOutput:
        """Fuse all modalities for a single signature."""
        embeddings = {
            'numeric': encode_numeric(p, q, r),
            'structural': encode_structural(p, q, r),
            'semantic': encode_semantic(p, q, r, brain_patterns),
        }
        return self.fusion.fuse(embeddings)

    def _classify_certificate(self, fout: FusionOutput, p: int, q: int, r: int) -> CertificateType:
        """Classify the certificate type based on fusion output.

        Decision logic:
            - If regime is decidable by native_decide → COMPUTATION
            - If signature matches known proof pattern → REDUCTION
            - If fusion energy is low (weak signal) → HEURISTIC
            - Otherwise → CONDITIONAL
        """
        kappa = 1.0/p + 1.0/q + 1.0/r

        # Regime classification is always decidable → at least COMPUTATION
        # for the regime theorem itself
        if abs(kappa - 1.0) > 0.01:
            # Clear spherical or hyperbolic → native_decide will work
            return CertificateType.COMPUTATION

        # Euclidean boundary cases need more care
        if abs(kappa - 1.0) < 1e-10:
            return CertificateType.COMPUTATION

        # Transitional → heuristic unless matched to known pattern
        if self._prototypes:
            best_sim = max(
                _cosine(fout.fused, proto)
                for proto in self._prototypes.values()
            )
            if best_sim > self.cert_threshold:
                return CertificateType.COMPUTATION
            elif best_sim > 0.3:
                return CertificateType.CONDITIONAL

        return CertificateType.HEURISTIC

    def generate(self, p: int, q: int, r: int,
                 brain_patterns: Optional[Dict] = None) -> LeanOutput:
        """Generate Lean 4 code for a Beal signature via tensor fusion.

        Args:
            p, q, r: exponents
            brain_patterns: optional dict of brain HDC patterns for semantic encoding

        Returns:
            LeanOutput with Lean code and certificate typing
        """
        # Step 1: Fuse
        fout = self._fuse_signature(p, q, r, brain_patterns)

        # Step 2: Classify
        kappa = 1.0/p + 1.0/q + 1.0/r
        if kappa > 1.0:
            regime = Regime.SPHERICAL
        elif abs(kappa - 1.0) < 0.01:
            regime = Regime.EUCLIDEAN
        else:
            regime = Regime.HYPERBOLIC

        cert_type = self._classify_certificate(fout, p, q, r)

        # Step 3: Generate Lean
        lean_code = self._emit_lean(p, q, r, kappa, regime, cert_type, fout)

        return LeanOutput(
            signature=(p, q, r),
            regime=regime,
            kappa=kappa,
            cert_type=cert_type,
            lean_code=lean_code,
            fusion_energy=fout.fusion_energy,
            recon_proxy=fout.recon_proxy,
            fused_vector=fout.fused,
        )

    def _emit_lean(self, p: int, q: int, r: int,
                    kappa: float, regime: Regime,
                    cert_type: CertificateType,
                    fout: FusionOutput) -> str:
        """Emit Lean 4 code with governance-typed certificates."""
        parts = []

        # Signature definition + regime theorem
        parts.append(LEAN_SIGNATURE_DEF.format(
            p=p, q=q, r=r,
            kappa=kappa,
            regime=regime.value,
        ))

        # Certificate
        cert_lean_map = {
            CertificateType.PROOF: "proof",
            CertificateType.REDUCTION: "reduction",
            CertificateType.COMPUTATION: "computation",
            CertificateType.CONDITIONAL: "conditional",
            CertificateType.HEURISTIC: "heuristic",
        }
        seam_map = {
            CertificateType.PROOF: "none",
            CertificateType.REDUCTION: "reduction target verification",
            CertificateType.COMPUTATION: "native_decide verification",
            CertificateType.CONDITIONAL: "depends on unproved conjecture",
            CertificateType.HEURISTIC: "tensor fusion heuristic only",
        }

        parts.append(LEAN_CERT_TEMPLATE.format(
            p=p, q=q, r=r,
            cert_type=cert_type.name,
            cert_lean=cert_lean_map[cert_type],
            reference=f"Darmon-Granville regime ({regime.value}), κ={kappa:.6f}",
            seam=seam_map[cert_type],
            fusion_energy=fout.fusion_energy,
            recon_proxy=fout.recon_proxy,
        ))

        # Obstruction theorem (for hyperbolic signatures)
        if regime == Regime.HYPERBOLIC:
            parts.append(LEAN_OBSTRUCTION_TEMPLATE.format(
                p=p, q=q, r=r,
                regime=regime.value,
                cert_type=cert_type.name,
            ))

        # Lock status
        is_hard = cert_type.value >= CertificateType.COMPUTATION.value
        parts.append(LEAN_BEAL_LOCK_TEMPLATE.format(
            p=p, q=q, r=r,
            hard_status="hard" if is_hard else "not_hard",
            hard_bool="true" if is_hard else "false",
            can_cannot="CAN" if is_hard else "CANNOT",
        ))

        return "\n".join(parts)

    def generate_batch(self, signatures: List[Tuple[int, int, int]],
                       output_path: Optional[Path] = None) -> List[LeanOutput]:
        """Generate Lean code for multiple signatures.

        If output_path is provided, writes a combined .lean file.
        """
        outputs = [self.generate(p, q, r) for p, q, r in signatures]

        if output_path:
            header = """import BealFoundry.Governance
import BealFoundry.Lambda
import BealFoundry.Soundness
import BealFoundry.Observer

/-!
# Tensor Fusion Generated Signatures

Auto-generated by tensor_lean_bridge.py
Each signature has:
  - Regime classification (native_decide verified)
  - Certificate with governance typing
  - Obstruction theorem (hyperbolic cases)
  - Lock status (hard/not hard)

Certificate types reflect fusion confidence:
  - computation: regime decidable, native_decide verifies
  - conditional: depends on unproved conjecture
  - heuristic: tensor fusion heuristic only
-/

namespace BealFoundry
"""
            footer = "\nend BealFoundry\n"

            with open(output_path, 'w') as f:
                f.write(header)
                for out in outputs:
                    f.write(f"\n-- === Signature ({out.signature[0]},{out.signature[1]},{out.signature[2]}) ===\n")
                    f.write(f"-- Regime: {out.regime.value}, κ = {out.kappa:.6f}\n")
                    f.write(f"-- Certificate: {out.cert_type.name} (energy={out.fusion_energy:.4f})\n")
                    f.write(out.lean_code)
                f.write(footer)

        return outputs


def _cosine(a: np.ndarray, b: np.ndarray) -> float:
    na = np.linalg.norm(a)
    nb = np.linalg.norm(b)
    if na == 0 or nb == 0:
        return 0.0
    return float(np.dot(a, b) / (na * nb))


