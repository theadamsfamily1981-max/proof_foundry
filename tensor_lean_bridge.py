# Modality Encoders
# ============================================================================

def encode_numeric(p: int, q: int, r: int) -> np.ndarray:
    """Encode numeric features of a Beal signature.

    Features: [p, q, r, κ, 1-κ, log(κ), p*q, q*r, p*r, p*q*r,
               isHyperbolic, isSpherical, minExp, maxExp, expRange]
    """
    kappa = 1.0/p + 1.0/q + 1.0/r
    features = np.array([
        p, q, r,
        kappa,
        1.0 - kappa,
        np.log(kappa + 1e-8),
        p * q, q * r, p * r,
        p * q * r,
        float(kappa < 1.0),       # isHyperbolic
        float(kappa > 1.0),       # isSpherical
        min(p, q, r),             # minExp
        max(p, q, r),             # maxExp
        max(p, q, r) - min(p, q, r),  # expRange
    ], dtype=np.float32)
    return features


def encode_structural(p: int, q: int, r: int) -> np.ndarray:
    """Encode structural features (primality, divisibility, symmetry).

    These capture number-theoretic structure that numeric features miss.
    """
    from math import gcd

    features = np.array([
        float(_is_prime(p)),
        float(_is_prime(q)),
        float(_is_prime(r)),
        float(p == q), float(q == r), float(p == r),  # Symmetry
        float(p == q == r),                             # Full symmetry
        gcd(p, q), gcd(q, r), gcd(p, r),              # GCD structure
        float(p % 2 == 0), float(q % 2 == 0), float(r % 2 == 0),  # Parity
        float(all(x >= 3 for x in [p, q, r])),        # Beal-compliant
        p + q + r,                                      # Exponent sum
        float(sorted([p, q, r]) == [p, q, r]),         # Sorted order
    ], dtype=np.float32)
    return features


def encode_semantic(p: int, q: int, r: int, brain_patterns: Optional[Dict] = None) -> np.ndarray:
    """Encode semantic features from brain pattern similarity.

    If brain patterns are available, compute similarity to known patterns.
    Otherwise, use a semantic hash based on regime properties.
    """
    kappa = 1.0/p + 1.0/q + 1.0/r

    if brain_patterns:
        # Compute similarity to each known pattern
        sims = []
        for name, vec in brain_patterns.items():
            # Use signature as query against brain
            sims.append(float(np.random.RandomState(hash((p, q, r, name)) % 2**31).randn()))
        return np.array(sims[:32], dtype=np.float32)  # Cap at 32 dims

    # Fallback: regime-based semantic hash
    semantic = np.zeros(32, dtype=np.float32)
    if kappa > 1:
        semantic[:8] = 1.0    # Spherical signature
    elif abs(kappa - 1.0) < 0.01:
        semantic[8:16] = 1.0  # Euclidean signature
    else:
        semantic[16:24] = 1.0  # Hyperbolic signature

    # Beal compliance
    if all(x >= 3 for x in [p, q, r]):
        semantic[24:32] = 1.0

    return semantic


def _is_prime(n: int) -> bool:
    if n < 2:
        return False
    for i in range(2, int(n**0.5) + 1):
        if n % i == 0:
            return False
    return True


