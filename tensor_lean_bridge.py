# ============================================================================
# Certificate Types (mirrors Lean Governance.lean)
# ============================================================================

class CertificateType(Enum):
    PROOF = 5        # Complete, unconditional proof
    REDUCTION = 4    # Reduces to known result
    COMPUTATION = 3  # Verified by reproducible computation
    CONDITIONAL = 2  # Depends on unproved conjecture
    HEURISTIC = 1    # Numerical/probabilistic evidence only


class Regime(Enum):
    SPHERICAL = "spherical"    # κ > 1
    EUCLIDEAN = "euclidean"    # κ = 1
    HYPERBOLIC = "hyperbolic"  # κ < 1


