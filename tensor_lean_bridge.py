LEAN_SIGNATURE_DEF = """
/-- Signature ({p},{q},{r}): κ = {kappa:.6f}, regime = {regime}. -/
def sig{p}{q}{r} : Signature := ⟨{p}, {q}, {r}, by omega, by omega, by omega⟩

theorem sig{p}{q}{r}_{regime} : sig{p}{q}{r}.regime = .{regime} := by
  native_decide
"""

LEAN_CERT_TEMPLATE = """
/-- Certificate for ({p},{q},{r}): {cert_type} evidence.
    Fusion energy: {fusion_energy:.4f}, reconstruction proxy: {recon_proxy:.4f}
    Generated by tensor fusion bridge. -/
def cert_{p}_{q}_{r} : Certificate where
  certType := .{cert_lean}
  reference := "{reference}"
  seam := "{seam}"
  verifier := "tensor_fusion_bridge"
"""

LEAN_OBSTRUCTION_TEMPLATE = """
/-- Obstruction: ({p},{q},{r}) is {regime}, so Darmon-Granville gives finitely
    many primitive solutions. Certificate: {cert_type}. -/
theorem obstruction_{p}_{q}_{r} :
    sig{p}{q}{r}.regime = .{regime} := by
  native_decide
"""

LEAN_BEAL_LOCK_TEMPLATE = """
/-- The ({p},{q},{r}) certificate is {hard_status}.
    Therefore it {can_cannot} support a PROVEN lock. -/
theorem cert_{p}_{q}_{r}_{hard_status} :
    cert_{p}_{q}_{r}.isHard = {hard_bool} := by
  native_decide
"""


